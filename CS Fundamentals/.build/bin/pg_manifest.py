"""Run every Kotlin listing with a main() in lessons/*.html on the Kotlin Playground server, and write
assets/pg-runnable.js: the hashes of listings that compile and finish there, so playground.js shows a Run button.

usage: python3 pg_manifest.py [--report]      (results are cached in .build/cache/pgapi.json; re-run after edits)
A listing is NOT runnable when it fails to compile on the server (Java 17 APIs only, one file, no extra libraries
beyond kotlinx.coroutines and kotlinx.serialization), hits the 10 s / output limits, or needs files, stdin or the
network. Listings inside .practice are skipped (practice has its own runner).
"""
import html
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pgapi  # noqa: E402

W = Path(__file__).resolve().parents[2]
# Exceptions that mean "this needs the learner's machine", not "this is what the lesson shows"
ENV = ("java.io.FileNotFoundException", "java.nio.file.NoSuchFileException", "java.net.ConnectException",
       "java.security.AccessControlException", "java.net.UnknownHostException", "java.nio.file.AccessDeniedException",
       "java.lang.SecurityException", "java.net.SocketException", "java.io.IOException", "java.sql.SQLException",
       "java.lang.ClassNotFoundException", "java.lang.NoClassDefFoundError", "java.lang.UnsatisfiedLinkError")


def fnv(text):
    h = 0x811C9DC5
    units = text.encode("utf-16-le")
    for i in range(0, len(units), 2):
        h ^= units[i] | (units[i + 1] << 8)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def listings(page):
    s = page.read_text()
    # drop practice widgets: their listings are not standalone examples
    s = re.sub(r'<div class="practice".*?<details class="answer">.*?</details>\s*</div>', "", s, flags=re.S)
    for m in re.finditer(r'<pre[^>]*>\s*<code class="language-kotlin"[^>]*>(.*?)</code>\s*</pre>', s, re.S):
        text = html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip()
        if re.search(r"\bfun main\s*\(", text):
            yield text


def classify(text):
    r = pgapi.run(text)
    if not r["ok"]:
        return "compile: " + (r["errors"][0] if r["errors"] else "?")
    if "Evaluation stopped" in r["err"]:
        return "limit: " + r["err"].strip()[:80]
    if r["exc"] and r["exc"].split(":")[0] in ENV:
        return "env: " + r["exc"][:100]
    if "readln" in text or "readLine" in text or "System.in" in text:
        return "env: reads stdin"
    return "ok"


report = {}
runnable = set()
for page in sorted((W / "lessons").glob("0*.html")):
    for text in listings(page):
        verdict = classify(text)
        report.setdefault(page.name, []).append((verdict, text.split("\n")[0][:60]))
        if verdict == "ok":
            runnable.add(fnv(text))
(W / "assets" / "pg-runnable.js").write_text(
    "/* Generated by .build/bin/pg_manifest.py: hashes of Kotlin listings that run on the Kotlin Playground. */\n"
    f"window.PG_RUNNABLE = {json.dumps(sorted(runnable))};\n")
total = sum(len(v) for v in report.values())
print(f"{len(runnable)} runnable of {total} listings with main()")
if "--report" in sys.argv:
    for name, rows in report.items():
        for verdict, first in rows:
            if verdict != "ok":
                print(f"{name}: {verdict[:140]}  [{first}]")
