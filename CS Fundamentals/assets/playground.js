/* CS Fundamentals: run Kotlin in the page with the JetBrains Kotlin Playground.
 *
 * lesson.js loads this file; lessons don't include it themselves.
 * The Playground compiles and runs code on JetBrains' server (api.kotlinlang.org), so it needs internet, and the
 * page must come from http (Open Course.command), because that server rejects file:// pages.
 * Its server runs Kotlin 2.4.21 on Java 17. Java code can't run in the page: it gets a Copy button for IntelliJ.
 *
 * Components:
 *
 *   Runnable example: any Kotlin listing whose text is in pg-runnable.js (a list of hashes written by
 *   .build/bin/pg_manifest.py after running every listing on the Playground) gets a "Run" button.
 *   Listings inside an unanswered .quiz wait until the quiz is answered.
 *
 *   Practice (generated by build.py from <!--PRACTICE:lNN/practice/pK-->):
 *     <div class="practice" data-id="pK">
 *       … <pre class="pg-src"><code class="language-kotlin">starter</code></pre>
 *       <div class="pg-bar"><button class="btn pg-run">…</button> <span class="pg-status"></span></div>
 *       <details class="pg-checks">… <code>JUnit tests</code></details>   ← sent as a hidden file
 *     </div>
 *   A practice with data-lang="sql" runs in the browser instead, with sql.js (see setupSqlPractice).
 *   "Run the checks" turns the starter into an editor and runs the tests. Passing all of them marks the
 *   practice solved. The learner's code and solved state are saved in localStorage under csf:<lesson>:practice.
 */
(function () {
  const KOTLIN = "2.4.21";
  const SCRIPT = "https://unpkg.com/kotlin-playground@1.34.0/dist/playground.min.js";
  const here = document.currentScript ? document.currentScript.src : "";
  const lesson = document.body.dataset.lesson || "lesson";
  const KEY = "csf:" + lesson + ":practice";

  function load() {
    try { return JSON.parse(localStorage.getItem(KEY)) || {}; } catch (e) { return {}; }
  }
  function save(st) {
    try { localStorage.setItem(KEY, JSON.stringify(st)); } catch (e) { /* ignore */ }
  }
  const store = load();
  function entry(id) { return (store[id] ||= {}); }

  // Same hash as pg_manifest.py: FNV-1a over the UTF-16 code units of the trimmed listing.
  function hash(text) {
    let h = 0x811c9dc5;
    for (let i = 0; i < text.length; i++) {
      h ^= text.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h.toString(16).padStart(8, "0");
  }

  function addScript(src) {
    return new Promise((ok, fail) => {
      const s = document.createElement("script");
      s.src = src;
      s.onload = ok;
      s.onerror = fail;
      document.head.appendChild(s);
    });
  }
  let playground = null;
  function playgroundReady() {
    if (FROM_DISK) return Promise.reject(new Error("file://"));
    playground ||= addScript(SCRIPT).then(() => {
      if (typeof window.KotlinPlayground !== "function") throw new Error("KotlinPlayground missing");
    });
    playground.catch(() => { playground = null; });   // let a later click retry
    return playground;
  }
  // The Playground server refuses pages opened from disk (their origin is "null"), so the course must be served
  // over http: double-click "Open Course.command" in the course folder (it runs the JDK's jwebserver).
  const FROM_DISK = location.protocol === "file:";
  const OFFLINE = FROM_DISK
    ? "Running code needs the course served over http. Double-click “Open Course.command” in the course folder, then use the page it opens."
    : "Couldn't reach the Kotlin Playground. It needs an internet connection. Copy the code into IntelliJ instead.";

  function dark() {
    const t = document.documentElement.dataset.theme;
    if (t) return t === "dark";
    return window.matchMedia && matchMedia("(prefers-color-scheme: dark)").matches;
  }

  // Replace a <pre> listing with a Playground editor. Resolves with the editor instance.
  function mount(pre, code, opts) {
    return playgroundReady().then(() => new Promise((resolve) => {
      const node = document.createElement("code");
      node.textContent = code;
      node.setAttribute("data-version", KOTLIN);
      node.setAttribute("theme", dark() ? "darcula" : "idea");
      node.setAttribute("lines", "true");
      node.setAttribute("match-brackets", "true");
      node.setAttribute("auto-indent", "true");
      node.setAttribute("indent", "4");
      if (opts.junit) node.setAttribute("data-target-platform", "junit");
      if (opts.hidden) {
        const ta = document.createElement("textarea");
        ta.className = "hidden-dependency";
        ta.textContent = opts.hidden;
        node.appendChild(ta);
      }
      const box = document.createElement("div");
      box.className = "pg-live";
      box.appendChild(node);
      pre.replaceWith(box);
      window.KotlinPlayground(node, {
        onChange: opts.onChange,
        onTestPassed: opts.onPass,
        onTestFailed: opts.onFail,
        getInstance: resolve,
      });
    }));
  }

  function button(label, cls) {
    const b = document.createElement("button");
    b.type = "button";
    b.className = "pg-btn " + (cls || "");
    b.textContent = label;
    return b;
  }

  function copyButton(pre) {
    const b = button("Copy", "ghost");
    b.addEventListener("click", () => {
      const text = pre.querySelector("code").textContent;
      const done = () => { b.textContent = "Copied ✓"; setTimeout(() => (b.textContent = "Copy"), 1500); };
      if (navigator.clipboard) navigator.clipboard.writeText(text).then(done, () => (b.textContent = "Select and ⌘C"));
      else b.textContent = "Select and ⌘C";
    });
    return b;
  }

  // ── Runnable examples ────────────────────────────────────
  function decorate(pre, runnable) {
    if (pre.dataset.pg) return;
    pre.dataset.pg = "1";
    const code = pre.querySelector("code");
    const text = code.textContent.trim();
    const kotlin = code.classList.contains("language-kotlin");
    const bar = document.createElement("div");
    bar.className = "pg-tools";
    if (kotlin && runnable.has(hash(text))) {
      const run = button("▶ Run");
      const note = document.createElement("span");
      note.className = "pg-note";
      run.addEventListener("click", () => {
        run.disabled = true;
        note.textContent = "loading the Kotlin Playground…";
        mount(pre, text, {}).then((inst) => {
          note.textContent = "Edit it and press ▶ in the editor to run again.";
          run.remove();
          inst.execute();
        }, () => { run.disabled = false; note.textContent = OFFLINE; });
      });
      bar.append(run, note);
    } else if (!kotlin && /static void main\s*\(|void main\s*\(\s*\)/.test(text)) {
      const note = document.createElement("span");
      note.className = "pg-note";
      note.textContent = "Java runs in IntelliJ, not in the page.";
      bar.append(copyButton(pre), note);
    } else return;
    pre.after(bar);
  }

  function decorateAll(runnable) {
    document.querySelectorAll("pre > code.language-kotlin, pre > code.language-java").forEach((code) => {
      const pre = code.parentElement;
      if (pre.closest(".practice, .memviz, .pg-live")) return;
      const quiz = pre.closest(".quiz");
      if (quiz && !quiz.classList.contains("answered")) {
        quiz.addEventListener("quiz:answered", () => decorate(pre, runnable), { once: true });
        return;
      }
      decorate(pre, runnable);
    });
  }

  // ── Practice ─────────────────────────────────────────────
  function setupPractice(box) {
    const id = box.dataset.id;
    const pre = box.querySelector("pre.pg-src");
    const runBtn = box.querySelector(".pg-run");
    const status = box.querySelector(".pg-status");
    const tests = box.querySelector(".pg-checks code").textContent.trim();
    const starter = pre.querySelector("code").textContent.trim();
    const e = entry(id);
    let editor = null;

    function show(kind, msg) {
      status.className = "pg-status " + kind;
      status.textContent = msg;
    }
    if (e.solved) { box.classList.add("solved"); show("ok", "✓ Solved before. Run it again any time."); }

    // The Playground reports passing and failing tests, but sends no event when the code doesn't compile.
    // So after each run, wait for its loader to go away; no verdict by then means compile errors.
    let pending = false;
    function run(inst) {
      pending = true;
      show("", "running…");
      inst.execute();
      let ticks = 0;
      const poll = setInterval(() => {
        ticks++;
        if (!pending) return clearInterval(poll);
        if (ticks > 4 && !box.querySelector(".loader")) {
          clearInterval(poll);
          pending = false;
          show("no", "✗ It doesn't compile yet. The red lines (and red marks in the editor) say where and why.");
        } else if (ticks > 240) {
          clearInterval(poll);
          pending = false;
          show("no", "✗ No answer from the Kotlin Playground. Check your connection and run again.");
        }
      }, 250);
    }

    function onPass() {
      pending = false;
      e.solved = true; save(store);
      box.classList.add("solved");
      show("ok", "✓ All checks pass. Saved as solved. Compare with the final answer below.");
    }
    function onFail() {
      pending = false;
      e.tries = (e.tries || 0) + 1; save(store);
      show("no", "✗ Not yet. Read the red lines in the output, then try again" + (e.tries > 1 ? " or open the next hint." : "."));
    }

    runBtn.addEventListener("click", () => {
      if (editor) { run(editor); return; }
      runBtn.disabled = true;
      show("", "loading the Kotlin Playground…");
      mount(pre, e.code || starter, {
        junit: true,
        hidden: tests,
        onPass, onFail,
        onChange: (code) => { e.code = code; save(store); },
      }).then((inst) => {
        editor = inst;
        runBtn.disabled = false;
        runBtn.textContent = "▶ Run the checks again";
        const reset = button("↺ Back to the starter code", "ghost");
        reset.addEventListener("click", () => {
          if (!confirm("Replace your code with the starter code?")) return;
          inst.codemirror.setValue(starter);
          delete e.code; save(store);
        });
        runBtn.after(" ", reset);
        run(inst);
      }, () => { runBtn.disabled = false; show("no", OFFLINE); });
    });
  }

  // ── SQL practice (sql.js: SQLite compiled to WebAssembly, runs in the browser, works from file:// too) ──
  const SQLJS = "https://cdnjs.cloudflare.com/ajax/libs/sql.js/1.15.1/";
  let sqlReady = null;
  function sqlEngine() {
    sqlReady ||= addScript(SQLJS + "sql-wasm.min.js").then(() => window.initSqlJs({ locateFile: (f) => SQLJS + f }));
    sqlReady.catch(() => { sqlReady = null; });
    return sqlReady;
  }

  // Run setup, then the statements; the answer is the last statement that returned rows (or the check query's).
  function runSql(SQL, setup, statements, check) {
    const db = new SQL.Database();
    try {
      db.exec(setup);
      let res = db.exec(statements);
      if (check) res = db.exec(check);
      return res.length ? res[res.length - 1] : { columns: [], values: [] };
    } finally { db.close(); }
  }

  function table(res) {
    if (!res.columns.length) return "<p class=\"pg-note\">No rows returned.</p>";
    const esc = (v) => String(v === null ? "NULL" : v).replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
    const head = res.columns.map((c) => `<th>${esc(c)}</th>`).join("");
    const body = res.values.slice(0, 50).map((r) => `<tr>${r.map((v) => `<td>${esc(v)}</td>`).join("")}</tr>`).join("");
    const more = res.values.length > 50 ? `<p class="pg-note">…and ${res.values.length - 50} more rows</p>` : "";
    return `<table class="sql-table"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>${more}`;
  }

  // Compare values only (column names may differ). Row order matters only if the solution sorts.
  function sameResult(got, want, ordered) {
    if (got.columns.length !== want.columns.length) return `Your result has ${got.columns.length} column(s); the task wants ${want.columns.length}.`;
    if (got.values.length !== want.values.length) return `Your result has ${got.values.length} row(s); the task wants ${want.values.length}.`;
    const key = (r) => JSON.stringify(r);
    const g = got.values.map(key), w = want.values.map(key);
    if (!ordered) { g.sort(); w.sort(); }
    const i = g.findIndex((r, k) => r !== w[k]);
    if (i === -1) return null;
    return ordered && [...g].sort().join() === [...w].sort().join()
      ? "The right rows, but in the wrong order."
      : `Row ${i + 1} of your result doesn't match what the task asks for.`;
  }

  function setupSqlPractice(box) {
    const id = box.dataset.id;
    const src = box.querySelector(".sql-src");
    const runBtn = box.querySelector(".pg-run");
    const status = box.querySelector(".pg-status");
    const out = box.querySelector(".sql-out");
    const setup = box.querySelector(".sql-setup code").textContent;
    const solution = box.querySelector(".sql-solution code").textContent;
    const check = box.querySelector(".sql-check")?.textContent || "";
    const starter = src.value;
    const ordered = /\border\s+by\b/i.test(check || solution);
    const e = entry(id);
    const show = (kind, msg) => { status.className = "pg-status " + kind; status.textContent = msg; };
    if (e.code) src.value = e.code;
    if (e.solved) { box.classList.add("solved"); show("ok", "✓ Solved before. Run it again any time."); }

    src.addEventListener("input", () => { e.code = src.value; save(store); });
    src.addEventListener("keydown", (ev) => {
      if (ev.key === "Tab") {
        ev.preventDefault();
        src.setRangeText("    ", src.selectionStart, src.selectionEnd, "end");
      } else if (ev.key === "Enter" && (ev.metaKey || ev.ctrlKey)) {
        ev.preventDefault();
        runBtn.click();
      }
    });

    runBtn.addEventListener("click", () => {
      show("", "running…");
      sqlEngine().then((SQL) => {
        let got;
        try { got = runSql(SQL, setup, src.value, check); }
        catch (err) {
          out.innerHTML = "";
          e.tries = (e.tries || 0) + 1; save(store);
          return show("no", "✗ SQLite error: " + err.message);
        }
        const want = runSql(SQL, setup, solution, check);
        out.innerHTML = table(got);
        const diff = sameResult(got, want, ordered);
        if (diff) {
          e.tries = (e.tries || 0) + 1; save(store);
          show("no", "✗ " + diff + (e.tries > 1 ? " Try the next hint." : ""));
        } else {
          e.solved = true; save(store);
          box.classList.add("solved");
          show("ok", "✓ That's the expected result. Saved as solved. Compare with the final answer below.");
        }
      }, () => show("no", "Couldn't load SQLite for the browser. It downloads once from cdnjs, so it needs an internet connection."));
    });

    const reset = button("↺ Back to the starter query", "ghost");
    reset.addEventListener("click", () => {
      if (!confirm("Replace your query with the starter query?")) return;
      src.value = starter;
      delete e.code; save(store);
    });
    runBtn.after(" ", reset);
  }

  document.querySelectorAll(".practice").forEach((box) =>
    box.dataset.lang === "sql" ? setupSqlPractice(box) : setupPractice(box));

  // pg-runnable.js sets window.PG_RUNNABLE to an array of listing hashes.
  const manifest = here ? new URL("pg-runnable.js", here).href : "../assets/pg-runnable.js";
  addScript(manifest).then(
    () => decorateAll(new Set(window.PG_RUNNABLE || [])),
    () => decorateAll(new Set())
  );
})();
